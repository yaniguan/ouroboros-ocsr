def _ensure_assigned_stereo(smiles: str, seed: int) -> str | None:
    std = standardize(smiles)
    if not std.valid or std.mol is None:
        return None
    has_unspec = any(
        el.specified == Chem.StereoSpecified.Unspecified
        for el in Chem.FindPotentialStereo(Chem.Mol(std.mol))
    )
    if not has_unspec:
        return std.smiles
    mol3d, _ = embed(std.smiles, n_conf=1, seed=seed)
    if mol3d is None:
        return None
    return stereo_from_3d(mol3d, 0)


def _compact_entry(
    idx: int, domain: str, name: str, subcat: str, smi: str, res: dict[str, Any]
) -> dict[str, Any]:
    s3d = res["structure_3d"]
    eq = res["equivariance_metrics"]
    atoms = s3d["atoms"]
    bonds = s3d["bonds"]
    cip_map = {int(a["idx"]): a["cip"] for a in atoms if a.get("cip")}
    entry: dict[str, Any] = {
        "id": f"{domain[:3]}_{idx:03d}",
        "name": name,
        "domain": domain,
        "sub": subcat,
        "smiles": res["standardized_smiles"] or smi,
        "formula": res["formula"],
        "mw": round(float(res["molecular_weight"]), 2),
        "mirror": res["mirror_relation"],
        "e": round(float(res["conformers"][0]["energy_ev"]), 4),
        "fmax": round(float(res["conformers"][0]["fmax_ev_a"]), 5),
        "dmin": round(float(s3d["d_min_a"]), 3),
        "bdev": round(max((float(b["deviation_a"]) for b in bonds), default=0.0), 4),
        "eq": [
            round(float(eq["se3_energy_abs_err_ev"]), 8),
            round(float(eq["so3_force_max_err_ev_a"]), 8),
            round(float(eq["net_force_norm_ev_a"]), 8),
            round(float(eq["conservative_grad_fd_err_ev_a"]), 6),
        ],
        "sym": [a["symbol"] for a in atoms],
        "xyz": [[round(float(a["x"]), 3), round(float(a["y"]), 3), round(float(a["z_coord"]), 3)] for a in atoms],
        "frc": [[round(float(a["fx"]), 4), round(float(a["fy"]), 4), round(float(a["fz"]), 4)] for a in atoms],
        "bnd": [[int(b["u"]), int(b["v"]), round(float(b["order"]), 1)] for b in bonds],
    }
    if cip_map:
        entry["cip"] = cip_map
    return entry


def build_catalog() -> dict[str, Any]:
    seen_ik: set[str] = set()
    bio_entries: list[dict[str, Any]] = []
    elec_entries: list[dict[str, Any]] = []
    skipped: list[tuple[str, str, str]] = []

    for domain, target, pool, bucket in (
        ("bio", TARGET_BIO, BIO_CANDIDATES, bio_entries),
        ("electrolyte", TARGET_ELECTROLYTE, ELECTROLYTE_CANDIDATES, elec_entries),
    ):
        for seed_idx, (name, subcat, raw_smi) in enumerate(pool):
            if len(bucket) >= target:
                break
            iso_smi = _ensure_assigned_stereo(raw_smi, seed=seed_idx)
            if not iso_smi:
                skipped.append((domain, name, "invalid_or_unembeddable"))
                continue
            std = standardize(iso_smi)
            ik = standard_inchikey(std) if std.valid else None
            if not ik or ik in seen_ik:
                skipped.append((domain, name, "duplicate_or_no_ik"))
                continue
            res = audit_3d_physical_compliance(
                iso_smi,
                potential="mmff94s",
                n_conf=1,
                do_relax=True,
                steps=200,
                expand_abbrev=False,
            )
            if res["overall_status"] != "pass":
                failed_gates = [g["id"] for g in res["gates"] if g["status"] != "pass"]
                skipped.append((domain, name, f"{res['overall_status']}:{failed_gates}"))
                continue
            seen_ik.add(ik)
            bucket.append(_compact_entry(len(bucket) + 1, domain, name, subcat, iso_smi, res))

    print(f"Bio built: {len(bio_entries)}/{TARGET_BIO}; Electrolyte built: {len(elec_entries)}/{TARGET_ELECTROLYTE}")
    if skipped:
        print(f"Skipped {len(skipped)} candidates (first 8): {skipped[:8]}")
    if len(bio_entries) != TARGET_BIO or len(elec_entries) != TARGET_ELECTROLYTE:
        raise RuntimeError(
            f"Count shortfall: bio={len(bio_entries)}/{TARGET_BIO}, "
            f"electrolyte={len(elec_entries)}/{TARGET_ELECTROLYTE}"
        )

    molecules = [*bio_entries, *elec_entries]
    return {
        "schema": "ouroboros.molecule_catalog_3d/v1",
        "potential": "RDKit ETKDGv3 + MMFF94s",
        "counts": {
            "total": len(molecules),
            "bio": len(bio_entries),
            "electrolyte": len(elec_entries),
        },
        "public_databases": [
            {
                "id": "pubchem",
                "name": "NCBI PubChem 3D (118M+ compounds)",
                "url": "https://pubchem.ncbi.nlm.nih.gov",
            },
            {
                "id": "chembl",
                "name": "EBI ChEMBL Bioactive Drugs (2.4M+ compounds)",
                "url": "https://www.ebi.ac.uk/chembl",
            },
        ],
        "molecules": molecules,
    }


def main() -> None:
    dst = ROOT / "site" / "assets" / "molecule-catalog-500.json"
    dst.parent.mkdir(parents=True, exist_ok=True)
    catalog = build_catalog()
    dst.write_text(json.dumps(catalog, separators=(",", ":")) + "\n", encoding="utf-8")
    print(f"Wrote {dst} ({dst.stat().st_size / 1024:.1f} KB)")


if __name__ == "__main__":
    main()
